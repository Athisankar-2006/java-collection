import java.util.PriorityQueue;

public class demopq3 {

      public static void main(String[] args) {
        
        PriorityQueue <Integer> pq= new PriorityQueue<>();
        pq.add(10);
        pq.add(30);
        pq.add(20);

        
       for(int i:pq){
       System.out.println(i);
       }
    }
    
    
}
